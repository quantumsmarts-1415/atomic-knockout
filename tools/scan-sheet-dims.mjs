// Writes src/campaign/sheetDims.js: the PNG size of every fighter sheet wider or taller than 4096 px.
// The campaign loader uses it to repack sheets that exceed the GPU texture limit *before* they reach
// WebGL (loading them straight in logs "texImage2D: width or height out of range").
// Run: node tools/scan-sheet-dims.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { CHARACTERS } from '../src/data/characters.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const big = {};
for (const c of Object.values(CHARACTERS)) {
  const s = c.art?.sheets;
  if (!c.art?.use3d || !s) continue;
  for (const [clip, def] of Object.entries(s.clips)) {
    const file = path.join(root, `${s.dir}${def.file || `${c.id}_${clip}.png`}`);
    if (!fs.existsSync(file)) continue;
    const fd = fs.openSync(file, 'r');
    const buf = Buffer.alloc(24);
    fs.readSync(fd, buf, 0, 24, 0);
    fs.closeSync(fd);
    if (buf.toString('latin1', 1, 4) !== 'PNG') continue;
    const w = buf.readUInt32BE(16);
    const h = buf.readUInt32BE(20);
    if (w > 4096 || h > 4096) big[`${c.art.key}-${clip}`] = [w, h];
  }
}
const body = Object.entries(big).sort().map(([k, v]) => `  '${k}': [${v[0]}, ${v[1]}],`).join('\n');
fs.writeFileSync(path.join(root, 'src/campaign/sheetDims.js'), `// Generated by tools/scan-sheet-dims.mjs. Fighter sheets over 4096 px: key -> [width, height].\nexport const BIG_SHEETS = {\n${body}\n};\n`);
console.log(`wrote ${Object.keys(big).length} entries`);
