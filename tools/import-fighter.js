function buildClip(folder, clipName, manifest, artHeight, referenceFrames) {
  const file = path.join(folder, `${clipName}.png`);
  if (!existsSync(file)) throw new Error(`missing ${clipName}.png in ${folder}`);
  const spec = manifest.clips?.[clipName];
  if (!spec) throw new Error(`manifest.clips.${clipName} is missing`);
  const frameW = spec.frameW ?? manifest.frameW;
  const frameH = spec.frameH ?? manifest.frameH;
  if (!(frameW > 0) || !(frameH > 0)) throw new Error(`frame size missing for ${clipName}`);
  const png = readPng(file);
  const strip = resolveStrip(png, frameW, frameH, spec.count, clipName);
  let frames = sliceFrames(png, strip.count, strip.frameW, strip.frameH);
  const box = unionBounds(frames, 2);
  frames = cropFrames(frames, box);
  let stretch = 1;
  if (clipName === 'walk' && referenceFrames?.length) {
    stretch = walkStretch(referenceFrames, frames);
    if (stretch > 1) {
      const dh = Math.max(1, Math.round(frames[0].height * stretch));
      frames = frames.map((frame) => downscale(frame, frame.width, dh));
    }
  }
  const measured = measureFrames(frames);
  const scale = scaleForBody(measured, artHeight);
  const dw = Math.max(8, Math.round(frames[0].width * scale));
  const dh = Math.max(8, Math.round(frames[0].height * scale));
  const fitted = frames.map((frame) => downscale(frame, dw, dh));
  const scaled = padBox(fitted, clipPadding(clipName, dw, dh));
  const layoutMeasure = measureFrames(scaled) ?? {
    bodyH: Math.max(1, Math.round((measured?.bodyH ?? artHeight) * scale)),
    footY: measured?.footY ?? manifest.footY ?? 0.95,
  };
  const layout = layoutNumbers(layoutMeasure, artHeight);
  if (manifest.footY && clipName === 'idle' && layoutMeasure == null) {
    layout.footY = manifest.footY;
  }
  return {
    strip,
    sheet: packGrid(scaled),
    frames: scaled,
    cropped: clipName === 'idle' ? frames : null,
    stretch,
    frameW: scaled[0].width,
    frameH: scaled[0].height,
    count: strip.count,
    fps: spec.fps ?? (clipName === 'walk' ? 10 : clipName === 'attack' ? 12 : 6),
    loop: clipName === 'attack' ? false : spec.loop !== false,
    ...layout,
    manifestCount: spec.count,
  };
}

export function importFighter(folder, options = {}) {
  const id = options.id || path.basename(path.resolve(folder));
  const manifestPath = path.join(folder, 'manifest.json');
  if (!existsSync(manifestPath)) throw new Error(`no manifest.json in ${folder}`);
  const manifest = readJson(manifestPath);
  const metaPath = options.meta || defaultMeta(id);
  if (!metaPath) throw new Error(`no fighters/${id}.json — pass --meta with element stats`);
  const meta = readJson(metaPath);
  if (!meta.elementData) throw new Error(`${metaPath} needs elementData`);
  if (!meta.palettes?.length) throw new Error(`${metaPath} needs at least one palette`);
  const artHeight = Number(options.height || meta.height || 132);
  const built = {};
  for (const clip of CLIPS) {
    built[clip] = buildClip(folder, clip, manifest, artHeight, clip === 'walk' ? built.idle?.cropped : null);
  }

  mkdirSync(SHEET_DIR, { recursive: true });
  mkdirSync(PORTRAIT_DIR, { recursive: true });
  for (const clip of CLIPS) {
    const out = path.join(SHEET_DIR, `${id}_${clip}.png`);
    writeFileSync(out, PNG.sync.write(built[clip].sheet));
  }

  const portraitSrc = options.portrait || defaultPortrait(folder, id);
  const portraitRel = `art-src/imported/${id}-cut.png`;
  const portraitAbs = path.join(ROOT, portraitRel);
  if (portraitSrc) {
    writeFileSync(portraitAbs, PNG.sync.write(fitPortrait(readPng(portraitSrc))));
  } else if (!existsSync(portraitAbs)) {
    throw new Error('no portrait — pass --portrait or place portraits/<id>-cut.png next to the sprite folder');
  }

  const idle = built.idle;
  const clipEntry = (clip) => {
    const b = built[clip];
    const entry = {
      count: b.count,
      fps: b.fps,
      loop: b.loop,
      frameW: b.frameW,
      frameH: b.frameH,
      footY: b.footY,
      visibleH: b.visibleH,
      bodyH: b.bodyH,
      displayScale: b.displayScale,
    };
    return entry;
  };
  const record = {
    id,
    name: meta.name || id,
    element: meta.element || meta.name || id,
    symbol: meta.symbol || id.slice(0, 2),
    atomicNumber: meta.atomicNumber,
    tagline: meta.tagline || '',
    teach: meta.teach || '',
    ghost: !!meta.ghost,
    height: artHeight,
    facing: meta.facing ?? 1,
    airJumps: meta.airJumps ?? 1,
    bodyW: meta.bodyW ?? Math.round(artHeight * 0.34),
    bodyH: meta.bodyH ?? Math.round(artHeight * 0.88),
    palettes: meta.palettes,
    body: meta.body,
    elementData: meta.elementData,
    art: {
      key: `char-${id}`,
      file: portraitRel,
      facing: meta.facing ?? 1,
      sheets: {
        dir: 'art-src/imported/sheets/',
        frameW: idle.frameW,
        frameH: idle.frameH,
        footY: idle.footY,
        visibleH: idle.visibleH,
        bodyH: idle.bodyH,
        displayScale: idle.displayScale,
        clips: {
          idle: clipEntry('idle'),
          walk: clipEntry('walk'),
          attack: clipEntry('attack'),
        },
      },
    },
  };

  const roster = loadRoster();
  roster[id] = record;
  writeRoster(roster);
  return { id, record, built };
}

function main() {
  const { folder, named } = parseArgs(process.argv);
  if (!folder || named.help) {
    console.error('Usage: node tools/import-fighter.js <folder> [--portrait png] [--meta json] [--id id] [--height px]');
    process.exit(folder ? 0 : 1);
  }
  const abs = path.resolve(folder);
  const result = importFighter(abs, {
    id: named.id,
    portrait: named.portrait ? path.resolve(named.portrait) : null,
    meta: named.meta ? path.resolve(named.meta) : null,
    height: named.height,
  });
  console.log(`registered ${result.id} (${result.record.element}) at ${result.record.height}px`);
  for (const clip of CLIPS) {
    const b = result.built[clip];
    const note = b.manifestCount !== b.count ? ` manifest said ${b.manifestCount}` : '';
    console.log(
      `  ${clip}: ${b.count} frames ${b.frameW}x${b.frameH} via ${b.strip.how}${note}`
      + `  footY ${b.footY} bodyH ${b.bodyH} scale ${b.displayScale}`
      + (b.stretch > 1 ? `  walk×${b.stretch.toFixed(2)}` : ''),
    );
  }
}

const invoked = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;
if (invoked) main();
