// Builds src/data/masks.js: one collision bitmask per animation frame.
//
//   node tools/build-masks.mjs
//
// Every clip registered on a fighter (idle, walk, attack) is measured.
// Jump and crouch have no sheets; the sim scales the live mask by the pose.
// walk12/ is source art that is not wired into the roster, so it is not packed.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { PNG } from 'pngjs';
import {
  CELL, clipScale, rasterFrame, packCells, strikeCells, pushFrom, ellipseCells, cellStats,
} from './maskRaster.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outFile = join(root, 'src/data/masks.js');

function loadPng(file) {
  return PNG.sync.read(readFileSync(file));
}

function framesOf(png, count, frameW, frameH, footY, scale, facing, bodyH) {
  const specs = [];
  const bodies = [];
  const n = Math.max(1, count | 0);
  for (let i = 0; i < n; i++) {
    const solids = rasterFrame(png, i, frameW, frameH, footY, scale, facing, bodyH);
    bodies.push(solids);
    specs.push(packCells(solids));
  }
  return { specs, bodies };
}

async function main() {
  const { ROSTER } = await import(join(root, 'src/data/characters.js'));
  const all = {};
  let frameCount = 0;
  let strikeCount = 0;
  for (const c of ROSTER) {
    const art = c.art;
    const sheets = art?.sheets;
    const facing = art?.facing ?? 1;
    const clips = {};
    const strike = {};
    let idleBody = null;
    const names = sheets?.clips ? Object.keys(sheets.clips) : [];
    names.sort((a, b) => (a === 'idle' ? -1 : b === 'idle' ? 1 : a.localeCompare(b)));
    for (const name of names) {
      const def = sheets.clips[name];
      const file = join(root, `${sheets.dir}${c.id}_${name}.png`);
      if (!existsSync(file) || art.use3d === false) continue;
      const png = loadPng(file);
      const lay = clipScale(art, sheets, def);
      const built = framesOf(
        png, def.count, lay.frameW, lay.frameH, lay.footY, lay.scale, facing, lay.bodyH,
      );
      const usable = built.specs.filter(Boolean);
      if (!usable.length) continue;
      clips[name] = built.specs;
      frameCount += built.specs.length;
      if (name === 'idle') idleBody = built.bodies[0];
      if (name === 'attack' || name === 'special') {
        const hits = built.bodies.map((body) => packCells(strikeCells(body, idleBody)));
        strike[name] = hits;
        strikeCount += hits.filter(Boolean).length;
      }
    }
    if (!clips.idle) {
      const synth = ellipseCells(art?.bodyW ?? 40, art?.bodyH ?? 110);
      clips.idle = [packCells(synth)];
      idleBody = synth;
      frameCount += 1;
    }
    const push = pushFrom(idleBody) || [-12, -70, 24, 68];
    const book = { clips, push };
    if (Object.keys(strike).length) book.strike = strike;
    all[c.id] = book;
    const idle0 = clips.idle?.[0];
    const stats = cellStats(idleBody || []);
    console.error(
      c.id,
      'frames', Object.values(clips).reduce((n, a) => n + a.length, 0),
      'idleCells', stats.n,
      'cx', stats.cx.toFixed(1),
      'pix', stats.pixelCx.toFixed(1),
      'w', stats.width.toFixed(0),
      'push', push.join(','),
      idle0 ? '' : 'SYNTH',
    );
  }
  const body = `// Generated by tools/build-masks.mjs. Do not edit by hand.
// Per-frame collision bitmasks, ${CELL}px cells, facing-right game pixels
// from the feet. A frame is "ox|oy|cols|rows|base64" (row-major bits).
// strike frames are the fist, blade, or projectile pixels on that attack
// frame, or null when the swing falls back to a swept arc.
export const CELL = ${CELL};
export const MASK_RAW = ${JSON.stringify(all)};
`;
  writeFileSync(outFile, body);
  console.log(`wrote ${Object.keys(all).length} fighters, ${frameCount} frames, ${strikeCount} strike masks, ${body.length} bytes`);
}

main();
